package com.nexters.gitit.domain.quizrepo

/**
 * 기계 검증이 남긴 의심 표시. 붙어도 데이터는 그대로 저장됩니다.
 *
 * 검증 실패를 폐기가 아니라 태그로 남기는 이유는 재생성 루프가 비용과 복잡도의 주범이기 때문입니다.
 * 재료가 부족해서 생긴 문제는 다시 만들어도 같은 결과이고, 태그는 서빙 필터의 재료가 되면서
 * 프롬프트를 어디부터 고쳐야 하는지도 알려줍니다.
 *
 * 심볼 인덱스가 없는 지금은 식별자 문자열 대조까지가 한계라, 판정이 아니라 의심입니다.
 */
enum class QualityTag {
    /** 산문(orientation·앵커 요약)이 대조 범위에 없는 식별자를 말하고 있습니다. */
    PROSE_SUSPECT,

    /** 오답 선택지가 대조 범위에 없는 식별자로 만들어졌습니다. 지어낸 이름은 소거법으로 걸러져 학습이 안 됩니다. */
    DISTRACTOR_SUSPECT,

    /** L3라면서 근거 앵커가 하나뿐입니다. 앵커를 연결해야 풀리는 문제가 아닐 가능성이 큽니다. */
    DEPTH_SUSPECT,
}
